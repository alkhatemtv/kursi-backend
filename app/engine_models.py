"""Kursi Engine ORM models (Phase 1a) - see docs/engine-phase1-schema-spec.md.

COEXISTENCE WITH THE LEGACY SCHEMA
----------------------------------
A legacy `events` table already exists and is read by the frozen marketplace, so the
Engine's own `events` table would collide with it. Every table defined here therefore
carries an ``engine_`` prefix (``engine_events``, ``engine_orders``, ...). The legacy
tables in `app/models.py` are untouched by this module.

Three tables here intentionally point *into* the legacy schema: `users` is shared
between both worlds per spec 1, so `engine_memberships.user_id`,
`engine_layout_versions.created_by_user_id`, `engine_tickets.checked_in_by_user_id`
and `engine_audit_log.actor_user_id` are FKs onto the existing `users.id`. Note that
`users.id` is INTEGER (legacy), not BIGINT, so those columns use Integer to match.

PORTABILITY
-----------
Production is PostgreSQL; the test harness defaults to SQLite (see TESTING.md). Every
Postgres-specific type is declared with a SQLite variant so the whole schema is
creatable on both:
    JSONB    -> JSON      (SQLite)
    TEXT[]   -> JSON      (SQLite)
    BIGINT   -> INTEGER   (SQLite, so Identity PKs autoincrement via the rowid alias)
`Identity()` renders as BIGINT GENERATED BY DEFAULT AS IDENTITY on Postgres and is
ignored by SQLite.

MONEY
-----
All money is an integer minor-unit amount plus an ISO currency, per spec 5. The
`MinorAmount` type below *rejects* floats and Decimals outright rather than letting the
driver silently round them - see its docstring.
"""
