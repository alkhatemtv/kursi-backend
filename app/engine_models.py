# ── Portable type aliases ───────────────────────────────────────────────────
#: BIGINT on Postgres, INTEGER on SQLite (so an Identity PK autoincrements there).
BigInt = BigInteger().with_variant(Integer(), "sqlite")
#: Legacy `users.id` is INTEGER - FKs onto it must match, not BigInt.
LegacyUserId = Integer
#: timestamptz per spec conventions.
TS = DateTime(timezone=True)
#: JSONB document, degraded to JSON on SQLite.
JSONDoc = JSONB().with_variant(JSON(), "sqlite")
#: TEXT[] on Postgres, JSON array on SQLite.
TextArray = ARRAY(Text()).with_variant(JSON(), "sqlite")
#: ISO-4217 currency code.
CurrencyCode = CHAR(3)


class MinorAmount(TypeDecorator):
    """BIGINT holding an amount in minor units (fils, cents), never a float.

    Exit test 6 requires that money can never be silently rounded. A plain BIGINT
    column does not give that: PostgreSQL will happily coerce ``100.5`` to ``101``,
    and SQLite will store ``100.5`` as-is in an INTEGER-affinity column. Neither is
    acceptable for money.

    Binding is therefore the enforcement point - it runs for ORM flushes *and* for
    Core inserts, on every dialect, before the driver ever sees the value. A float or
    Decimal raises TypeError instead of being rounded. Callers converting from a
    major-unit amount must do so explicitly (KWD 5.500 -> 5500).
    """

    impl = BigInteger
    cache_ok = True

    def process_bind_param(self, value, dialect):
        if value is None:
            return None
        # bool is a subclass of int; it is never a valid money amount.
        if isinstance(value, bool):
            raise TypeError(
                f"monetary value must be an integer number of minor units, got bool: {value!r}"
            )
        if isinstance(value, int):
            return value
        raise TypeError(
            f"monetary value must be an integer number of minor units, got "
            f"{type(value).__name__}: {value!r}. Money is never a float - convert "
            f"explicitly (e.g. KWD 5.500 -> 5500)."
        )


def _enum_check(table: str, column: str, values: tuple[str, ...]) -> CheckConstraint:
    """TEXT + CHECK for an enum-like state, per spec conventions.

    Readable in plain SQL and extensible without an ALTER TYPE dance, which is why the
    spec prefers it over a native enum.
    """
    rendered = ", ".join(f"'{v}'" for v in values)
    return CheckConstraint(f"{column} IN ({rendered})", name=f"ck_{table}_{column}")


def _non_negative(table: str, column: str) -> CheckConstraint:
    return CheckConstraint(f"{column} >= 0", name=f"ck_{table}_{column}_non_negative")


def _currency_shape(table: str, column: str = "currency") -> CheckConstraint:
    """ISO-4217 codes are exactly three characters. `length()` exists on both dialects."""
    return CheckConstraint(f"length({column}) = 3", name=f"ck_{table}_{column}_len")


def _pk() -> Mapped[int]:
    return mapped_column(BigInt, Identity(), primary_key=True)


class TimestampMixin:
    """created_at / updated_at timestamptz on every Engine table, per spec conventions."""

    created_at: Mapped[datetime] = mapped_column(
        TS, server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        TS, server_default=func.now(), onupdate=func.now(), nullable=False
    )


